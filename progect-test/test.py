def encode_image_to_base64(image_bytes: bytes) -> str:
    """Конвертация изображения в base64"""
    return base64.b64encode(image_bytes).decode('utf-8')


async def analyze_jewelry(image_data_list: list) -> str:
    """Отправка запроса к AI для анализа ювелирного изделия"""
    try:
        # Формируем содержимое сообщения с текстом и изображениями
        content = [
            {"type": "text", "text": JEWELRY_ANALYSIS_PROMPT}
        ]

        # Добавляем все изображения
        for image_data in image_data_list:
            content.append({
                "type": "image_url",
                "image_url": {
                    "url": f"data:image/jpeg;base64,{image_data}"
                }
            })

        # Отправляем запрос к API
        response = client_ai.chat.completions.create(
            model=AI_MODEL,
            messages=[
                {
                    "role": "user",
                    "content": content
                }
            ],
            max_tokens=4000,
            temperature=0.3,
        )

        return response.choices[0].message.content

    except Exception as e:
        return f"❌ <b>Ошибка при анализе изображения:</b> {str(e)}"


async def handle_photo(update: Update, context: ContextTypes.DEFAULT_TYPE):
    """Обработчик полученных фотографий"""
    try:
        # Инициализируем список фото, если его нет
        if 'photos' not in context.user_data:
            context.user_data['photos'] = []

        # Информируем пользователя о начале обработки
        processing_msg = await update.message.reply_text("📸 Получаю изображение...")

        # Получаем файл с максимальным разрешением
        photo = update.message.photo[-1]
        file = await context.bot.get_file(photo.file_id)

        # Скачиваем фото в память
        photo_bytes = await file.download_as_bytearray()

        # Конвертируем в base64
        base64_image = encode_image_to_base64(bytes(photo_bytes))

        # Добавляем в список фотографий пользователя
        context.user_data['photos'].append(base64_image)

        photo_count = len(context.user_data['photos'])

        # Обновляем сообщение
        await processing_msg.edit_text(
            f"✅ <b>Фото {photo_count} получено!</b>\n\n"
            f"Можете отправить еще фото или подождите несколько секунд для начала анализа...\n\n"
            f"<i>Используйте /clear чтобы очистить все фото и начать заново.</i>",
            parse_mode='HTML'
        )

        # Автоматически запускаем анализ через 3 секунды после последнего фото
        # Отменяем предыдущий таймер, если он был
        if 'analysis_job' in context.user_data and context.user_data['analysis_job']:
            context.user_data['analysis_job'].schedule_removal()

        # Создаем новый таймер
        context.user_data['analysis_job'] = context.job_queue.run_once(
            start_analysis, 
            3, 
            data={'chat_id': update.effective_chat.id, 'user_id': update.effective_user.id}
        )

    except Exception as e:
        await update.message.reply_text(
            f"❌ <b>Ошибка при обработке фото:</b> {str(e)}",
            parse_mode='HTML'
        )


async def start_analysis(context: ContextTypes.DEFAULT_TYPE):
    """Запуск анализа накопленных фотографий"""
    job_data = context.job.data
    chat_id = job_data['chat_id']
    user_id = job_data['user_id']

    # Получаем данные пользователя
    user_data = context.application.user_data.get(user_id, {})
    photos = user_data.get('photos', [])

    if not photos:
        return

    try:
        # Отправляем сообщение о начале анализа
        photo_word = "изображения" if len(photos) == 1 else "изображений"
        status_msg = await context.bot.send_message(
            chat_id=chat_id,
            text=f"🔍 <b>Начинаю детальный анализ {len(photos)} {photo_word}...</b>\n"
                 f"⏳ <i>Это может занять 20-40 секунд.</i>",
            parse_mode='HTML'
        )

        # Выполняем анализ
        analysis_result = await analyze_jewelry(photos)

        # Удаляем статусное сообщение
        await status_msg.delete()

        # Отправляем результат (разбиваем на части, если слишком длинный)
        max_length = 4000
        if len(analysis_result) <= max_length:
            await context.bot.send_message(
                chat_id=chat_id,
                text=analysis_result,
                parse_mode='HTML'
            )
        else:
            # Разбиваем длинное сообщение на части
            parts = [analysis_result[i:i+max_length] for i in range(0, len(analysis_result), max_length)]
            for i, part in enumerate(parts, 1):
                if i == 1:
                    header = f"<b>📋 РЕЗУЛЬТАТ АНАЛИЗА (часть {i}/{len(parts)})</b>\n{'='*30}\n\n"
                else:
                    header = f"\n<b>Продолжение (часть {i}/{len(parts)})</b>\n\n"

                await context.bot.send_message(
                    chat_id=chat_id,
                    text=f"{header}{part}",
                    parse_mode='HTML'
                )

        # Очищаем фото после анализа
        user_data['photos'] = []

        # Предлагаем отправить новые фото
        await context.bot.send_message(
            chat_id=chat_id,
            text="\n💡 <i>Можете отправить новые фотографии для анализа другого изделия!</i>",
            parse_mode='HTML'
        )

    except Exception as e:
        await context.bot.send_message(
            chat_id=chat_id,
            text=f"❌ <b>Произошла ошибка при анализе:</b> {str(e)}\n\n"
                 f"<i>Попробуйте отправить фото еще раз или используйте /help</i>",
            parse_mode='HTML'
        )


